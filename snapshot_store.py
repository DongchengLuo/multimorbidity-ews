#!/usr/bin/env python
# -*- coding: utf-8 -*-
"""
snapshot_store.py - local de-identified snapshot query layer

Purpose
----
Replaces all direct SQL Server queries in app.py under SNAPSHOT_MODE,
All data comes from the 6 isomorphic CSVs under data/snapshot/ (generated by tools/build_snapshot.py).

Public interface keeps the same semantics as app.py's original SQL:
    preload(limit)                      -> preload the patient list (with the first N details)
    patient_detail(app_no)              -> full record for one patient
    field_catalog()                     -> secondary-field dictionary
    search(conditions, page, page_size) -> multi-condition search (paged)
    search_app_nos(conditions, limit)   -> all app_no matching the conditions
    search_page_app_nos(...)            -> app_no within a page range
    watch_base_df()                     -> watch-directory basic-info table
    fetch_tables(app_nos)               -> the 6 tables persisted by db_fetcher

All data is loaded once read-only and cached; thread-safe (read-only).
"""

import os
import threading

import pandas as pd

ROOT = os.path.dirname(os.path.abspath(__file__))
SNAPSHOT_DIR = os.path.join(ROOT, "data", "snapshot")

BASE_COLS = [
    "app_no", "pat_id", "pat_name", "app_pat_name", "app_pat_age",
    "pat_sex", "pat_nation", "pat_address",
]

_lock = threading.Lock()
_cache = {}


# ---------------------------------------------------------------- Loading

def _read(name, usecols=None):
    path = os.path.join(SNAPSHOT_DIR, name)
    if not os.path.exists(path):
        raise FileNotFoundError(
            f"Snapshot file missing: {path}\nPlease run: python tools/build_snapshot.py"
        )
    return pd.read_csv(
        path, dtype=str, low_memory=False, usecols=usecols
    ).fillna("")


def load():
    """Load and cache snapshot tables (on first call)."""
    if "base" in _cache:
        return _cache
    with _lock:
        if "base" in _cache:
            return _cache

        apply_df = _read("PES_APPLY.csv", usecols=[
            "app_no", "pat_id", "app_pat_name", "app_pat_age", "app_time",
            "app_check_date", "app_co_depart",
        ])
        patient_df = _read("PES_PATIENT.csv", usecols=[
            "pat_id", "pat_name", "pat_sex", "pat_nation", "pat_address",
            "pat_birth_date", "pat_marriage", "pat_job",
        ])
        result_df = _read("PES_RESULT.csv", usecols=[
            "detail_id", "app_no", "res_itm_name", "res_value", "res_unit",
            "res_exp", "res_refl", "res_refu", "res_sum_flag", "res_itm_id",
        ])
        item_df = _read("PES_apply_item.csv", usecols=[
            "detail_id", "app_no", "det_com_name", "det_dep_name",
        ])
        desc_df = _read("PES_RESULT_DESC.csv")
        summary_df = _read("PES_SUMMARY_COMBINE.csv")

        for df in (apply_df, patient_df, result_df, item_df, desc_df, summary_df):
            for c in ("app_no", "pat_id", "detail_id"):
                if c in df.columns:
                    df[c] = df[c].astype(str).str.strip()

        # Basic-info wide table (equivalent to PES_APPLY INNER JOIN PES_PATIENT)
        base = apply_df[["app_no", "pat_id", "app_pat_name", "app_pat_age"]].merge(
            patient_df[["pat_id", "pat_name", "pat_sex", "pat_nation", "pat_address"]],
            on="pat_id", how="inner",
        )
        base = base[base["app_pat_name"].str.strip() == base["pat_name"].str.strip()]
        base = base[BASE_COLS].drop_duplicates(subset=["app_no"]).reset_index(drop=True)
        base["_age_num"] = pd.to_numeric(base["app_pat_age"], errors="coerce")

        # Attach det_com_name to lab results (equivalent to PES_RESULT INNER JOIN PES_apply_item)
        # detail_id is globally unique in the snapshot; use a map instead of merge for >5x faster loading
        item_slim = item_df[["detail_id", "det_com_name", "det_dep_name"]]
        item_slim = item_slim.drop_duplicates(subset=["detail_id"]).set_index("detail_id")
        lab = result_df.copy()
        lab["det_com_name"] = lab["detail_id"].map(item_slim["det_com_name"]).fillna("")
        lab["det_dep_name"] = lab["detail_id"].map(item_slim["det_dep_name"]).fillna("")
        # Match the SQL semantics: prefer res_itm_name, fall back to det_com_name
        lab["fieldName"] = lab["res_itm_name"].where(
            lab["res_itm_name"].str.strip() != "", lab["det_com_name"]
        )

        desc = desc_df.copy()
        desc["det_com_name"] = desc["detail_id"].map(item_slim["det_com_name"]).fillna("")
        desc["det_dep_name"] = desc["detail_id"].map(item_slim["det_dep_name"]).fillna("")

        _cache.update({
            "apply": apply_df,
            "patient": patient_df,
            "result": result_df,
            "item": item_df,
            "desc": desc_df,
            "summary": summary_df,
            "base": base,
            "lab": lab,
            "desc_merged": desc,
            "lab_by_app": {k: v for k, v in lab.groupby("app_no")},
            "desc_by_app": {k: v for k, v in desc.groupby("app_no")},
        })
        print(f"[OK] Snapshot loaded: {len(base)} patients, {len(lab)} lab rows, {len(desc)} desc rows")
        return _cache


# ---------------------------------------------------------------- Condition matching

def _apply_op(series: pd.Series, op: str, val) -> pd.Series:
    """Replicate the semantics of build_value_clause in app.py on a pandas Series."""
    s = series.astype(str).str.strip()
    if op == "is_null":
        return s.eq("")
    if op == "is_not_null":
        return s.ne("")
    if op in ("gt", "ge", "lt", "le"):
        num = pd.to_numeric(s, errors="coerce")
        try:
            v = float(str(val).strip())
        except (TypeError, ValueError):
            raise ValueError(f"Numeric comparison operator {op} requires a number, got {val!r}")
        return {"gt": num > v, "ge": num >= v, "lt": num < v, "le": num <= v}[op]
    if op == "contains":
        return s.str.contains(str(val), regex=False, na=False)
    if op == "not_contains":
        return ~s.str.contains(str(val), regex=False, na=False)
    if op == "starts_with":
        return s.str.startswith(str(val), na=False)
    if op == "ends_with":
        return s.str.endswith(str(val), na=False)
    if op == "eq":
        return s.eq(str(val).strip())
    if op == "ne":
        return s.ne(str(val).strip())
    return pd.Series(False, index=series.index)


def _condition_app_nos(cond: dict) -> set:
    """Return the set of app_no matching a single condition."""
    d = load()
    category = cond.get("category")
    sub_field = str(cond.get("subField", "")).strip()
    operator = cond.get("operator", "eq")
    val = cond.get("value", "")

    if category == "LAB_EXAM" and sub_field:
        lab = d["lab"]
        hit = lab[lab["fieldName"] == sub_field]
        if hit.empty:
            return set()
        mask = _apply_op(hit["res_value"], operator, val)
        return set(hit.loc[mask, "app_no"])

    if category == "DESC_EXAM" and sub_field:
        desc = d["desc_merged"]
        hit = desc[desc["det_com_name"] == sub_field]
        if hit.empty:
            return set()
        mask = _apply_op(hit["res_result"], operator, val)
        return set(hit.loc[mask, "app_no"])

    if category in BASE_COLS:
        base = d["base"]
        if category == "app_pat_age":
            mask = _apply_op(base["app_pat_age"], operator, val)
        else:
            mask = _apply_op(base[category], operator, val)
        return set(base.loc[mask, "app_no"])

    return set()


def _filtered_base(conditions: list) -> pd.DataFrame:
    """Filter the basic-info table by conditions; returns a DataFrame sorted by app_no descending."""
    d = load()
    base = d["base"]

    valid = []
    for idx, cond in enumerate(conditions):
        category = cond.get("category")
        sub_field = str(cond.get("subField", "")).strip()
        operator = cond.get("operator", "eq")
        val = cond.get("value", "")
        # Same semantics as the UI's activeSearchConditions(): ignore incomplete conditions
        if category in ("LAB_EXAM", "DESC_EXAM") and not sub_field:
            continue
        if operator not in ("is_null", "is_not_null") and str(val).strip() == "":
            continue
        valid.append((idx, cond))

    if not valid:
        return base.sort_values("app_no", ascending=False).reset_index(drop=True)

    universe = set(base["app_no"])
    result = None
    for idx, cond in valid:
        logic = "AND" if idx == 0 else ("OR" if cond.get("logic") == "OR" else "AND")
        hits = _condition_app_nos(cond) & universe
        if result is None:
            result = hits
        elif logic == "OR":
            result = result | hits
        else:
            result = result & hits
        if not result:
            break

    result = result or set()
    out = base[base["app_no"].isin(result)]
    return out.sort_values("app_no", ascending=False).reset_index(drop=True)


# ---------------------------------------------------------------- Detail attachment

def _attach(records: list, max_app_nos: int = 60) -> list:
    d = load()
    lab_by_app = d["lab_by_app"]
    desc_by_app = d["desc_by_app"]
    lab_cols = ["detail_id", "det_dep_name", "det_com_name", "res_itm_name",
                "fieldName", "res_value", "res_unit", "res_exp", "res_refl",
                "res_refu", "res_sum_flag"]
    desc_cols = ["detail_id", "det_dep_name", "det_com_name", "res_result"]

    for i, r in enumerate(records):
        key = str(r.get("app_no", "")).strip()
        if i < max_app_nos:
            ldf = lab_by_app.get(key)
            r["lab_items"] = (
                ldf[lab_cols].to_dict(orient="records") if ldf is not None else []
            )
            ddf = desc_by_app.get(key)
            r["desc_items"] = (
                ddf[desc_cols].to_dict(orient="records") if ddf is not None else []
            )
        else:
            r.setdefault("lab_items", [])
            r.setdefault("desc_items", [])
    return records


def _to_records(df: pd.DataFrame) -> list:
    cols = [c for c in BASE_COLS if c in df.columns]
    return df[cols].to_dict(orient="records")


# ---------------------------------------------------------------- Public interface

def preload(limit: int = 5000) -> dict:
    df = _filtered_base([]).head(limit)
    records = _attach(_to_records(df), max_app_nos=40)
    return {"total": len(records), "records": records}


def patient_detail(app_no: str) -> dict:
    d = load()
    row = d["base"][d["base"]["app_no"] == str(app_no).strip()]
    if row.empty:
        return {"app_no": app_no, "lab_items": [], "desc_items": []}
    rec = _to_records(row)[0]
    return _attach([rec], max_app_nos=1)[0]


def field_catalog() -> dict:
    d = load()
    lab = d["lab"]
    desc = d["desc_merged"]

    lab_fields = []
    for name, grp in lab.groupby("fieldName", sort=False):
        if not str(name).strip():
            continue
        first = grp.iloc[0]
        uniq = grp[["res_value", "res_unit", "res_exp"]].drop_duplicates().head(4)
        numeric = pd.to_numeric(uniq["res_value"], errors="coerce").notna().sum()
        lab_fields.append({
            "fieldName": str(name),
            "sourceCol": "res_itm_name" if str(first["res_itm_name"]).strip() else "det_com_name(fallback)",
            "dept": str(first["det_dep_name"]),
            "valueType": "number" if numeric >= max(1, len(uniq) / 2) else "text",
            "unit": str(first["res_unit"]),
            "refRange": str(first["res_exp"]),
            "samples": [
                {
                    "rawValue": str(r["res_value"]),
                    "display": f"{r['res_value']} {r['res_unit']}".strip(),
                    "refRange": str(r["res_exp"]),
                }
                for _, r in uniq.iterrows()
            ],
        })

    desc_fields = []
    for name, grp in desc.groupby("det_com_name", sort=False):
        if not str(name).strip():
            continue
        first = grp.iloc[0]
        uniq = grp["res_result"].drop_duplicates().head(3)
        desc_fields.append({
            "fieldName": str(name),
            "sourceCol": "det_com_name",
            "dept": str(first["det_dep_name"]),
            "valueType": "text",
            "unit": "",
            "samples": [
                {
                    "rawValue": str(t)[:10].strip(),
                    "display": f'"{str(t)[:45]}..."' if len(str(t)) > 45 else f'"{t}"',
                }
                for t in uniq
            ],
        })

    return {"lab_fields": lab_fields, "desc_fields": desc_fields}


def search(conditions: list, page: int = 1, page_size: int = 20) -> dict:
    df = _filtered_base(conditions)
    total = len(df)
    start = (page - 1) * page_size
    page_df = df.iloc[start:start + page_size]
    records = _attach(_to_records(page_df), max_app_nos=page_size)
    return {
        "total": total,
        "page": page,
        "page_size": page_size,
        "records": records,
        "timing": {"db_query_ms": 0.0, "total_server_ms": 0.0},
    }


def search_app_nos(conditions: list, limit: int = 20000) -> dict:
    df = _filtered_base(conditions)
    all_nos = df["app_no"].tolist()
    return {
        "app_nos": all_nos[:limit],
        "total": len(all_nos),
        "truncated": len(all_nos) > limit,
    }


def search_page_app_nos(conditions: list, from_page: int, to_page: int,
                        page_size: int) -> dict:
    df = _filtered_base(conditions)
    start = (from_page - 1) * page_size
    end = to_page * page_size
    return {
        "app_nos": df["app_no"].tolist()[start:end],
        "from_page": from_page,
        "to_page": to_page,
        "page_size": page_size,
        "total": len(df),
    }


def watch_base_df() -> pd.DataFrame:
    """Watch-directory basic-info table (derived from the snapshot in snapshot mode, limited to app_no in the manifest txt)."""
    d = load()
    df = d["base"].copy()

    # Read the manifest txt in the watch directory and keep only listed app_no (same as real mode)
    watch_dir = os.path.join(ROOT, "watched_app_nos")
    wanted = set()
    if os.path.isdir(watch_dir):
        for fn in os.listdir(watch_dir):
            if not fn.lower().endswith(".txt") or fn.startswith("."):
                continue
            try:
                with open(os.path.join(watch_dir, fn), encoding="utf-8", errors="ignore") as f:
                    for line in f:
                        t = line.strip()
                        if t:
                            wanted.add(t)
            except OSError:
                continue
    if wanted:
        df = df[df["app_no"].isin(wanted)]

    df["source_txt"] = "demo_list.txt"
    df["sync_time"] = pd.Timestamp.now().strftime("%Y-%m-%d %H:%M:%S")
    return df[["app_no", "pat_id", "pat_name", "app_pat_name", "app_pat_age",
               "pat_sex", "pat_nation", "pat_address", "source_txt", "sync_time"]]


def fetch_tables(app_nos: list) -> dict:
    """Return the 6 table DataFrames (full columns) for the given app_no, for db_fetcher to persist."""
    full = _full_tables()
    nos = {str(a).strip() for a in app_nos if str(a).strip()}
    out = {}
    for key, fname in (
        ("apply", "PES_APPLY.csv"),
        ("patient", "PES_PATIENT.csv"),
        ("result", "PES_RESULT.csv"),
        ("item", "PES_apply_item.csv"),
        ("desc", "PES_RESULT_DESC.csv"),
        ("summary", "PES_SUMMARY_COMBINE.csv"),
    ):
        df = full[key]
        if key == "patient":
            pat_ids = set(full["apply"].loc[full["apply"]["app_no"].isin(nos), "pat_id"])
            out[fname] = df[df["pat_id"].isin(pat_ids)].copy()
        else:
            out[fname] = df[df["app_no"].isin(nos)].copy()
    return out


def _full_tables() -> dict:
    """Load full-column tables on demand (export pipeline only, to avoid resident memory)."""
    if "_full" in _cache:
        return _cache["_full"]
    with _lock:
        if "_full" not in _cache:
            full = {}
            for key, fname in (
                ("apply", "PES_APPLY.csv"),
                ("patient", "PES_PATIENT.csv"),
                ("result", "PES_RESULT.csv"),
                ("item", "PES_apply_item.csv"),
                ("desc", "PES_RESULT_DESC.csv"),
                ("summary", "PES_SUMMARY_COMBINE.csv"),
            ):
                df = _read(fname)
                for c in ("app_no", "pat_id", "detail_id"):
                    if c in df.columns:
                        df[c] = df[c].astype(str).str.strip()
                full[key] = df
            _cache["_full"] = full
    return _cache["_full"]


def is_available() -> bool:
    return os.path.exists(os.path.join(SNAPSHOT_DIR, "PES_PATIENT.csv"))
